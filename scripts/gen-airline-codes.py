#!/usr/bin/env python3
"""Regenerate html/ui/airline-codes.js (ICAO airline prefix -> IATA code) from Wikidata.

Wikidata data is CC0 1.0 (public domain dedication): https://www.wikidata.org/wiki/Wikidata:Licensing
Used by ui/airlines.js to find airline logos by IATA code. Only active airlines (no end date) that have
both an ICAO (P230) and an IATA (P229) designator are included. ICAO codes that map to different IATA
codes are dropped, except the hand-checked overrides below.

The logo provider (pics.avs.io, see airlineLogoUrl in html/defaults.js) is probed once per airline, so the page only
ever requests logos that exist (a missing logo is a 404 the browser logs). Only the list of airlines that have a logo
is stored, never the images. Use --no-probe to skip probing (then every mapped airline is tried at run time).

Usage: python3 scripts/gen-airline-codes.py [--no-probe]
"""
import collections, concurrent.futures, datetime, json, os, sys, urllib.parse, urllib.request

QUERY = """
SELECT ?icao ?iata WHERE {
  ?a wdt:P230 ?icao ; wdt:P229 ?iata .
  FILTER NOT EXISTS { ?a wdt:P576 ?end }
}
"""
OVERRIDES = {'THY': 'TK', 'KQA': 'KQ'}   # Turkish Airlines, Kenya Airways: Wikidata lists several entities each

req = urllib.request.Request(
    'https://query.wikidata.org/sparql?' + urllib.parse.urlencode({'query': QUERY}),
    headers={'Accept': 'application/sparql-results+json', 'User-Agent': 'skywatch-gen-airline-codes/1.0'})
rows = json.load(urllib.request.urlopen(req, timeout=120))['results']['bindings']

found = collections.defaultdict(set)
for r in rows:
    icao, iata = r['icao']['value'].strip().upper(), r['iata']['value'].strip().upper()
    if len(icao) == 3 and icao.isalpha() and len(iata) == 2 and iata.isalnum():
        found[icao].add(iata)

out = {}
for icao, codes in sorted(found.items()):
    if icao in OVERRIDES:
        out[icao] = OVERRIDES[icao]
    elif len(codes) == 1:
        out[icao] = next(iter(codes))

LOGO = 'https://pics.avs.io/al_square/128/128/%s.png'

def logo_size(iata):
    try:
        r = urllib.request.urlopen(urllib.request.Request(LOGO % iata, headers={'User-Agent': 'skywatch-gen-airline-codes/1.0'}), timeout=30)
        return len(r.read()) if r.status == 200 else -1
    except Exception:
        return -1

has_logo = None
if '--no-probe' not in sys.argv:
    placeholder = logo_size('XX')      # the provider's generic image for unknown codes
    iatas = sorted(set(out.values()))
    print('probing %d IATA codes (placeholder is %d bytes)...' % (len(iatas), placeholder))
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as ex:
        sizes = dict(zip(iatas, ex.map(logo_size, iatas)))
    ok = {i for i, n in sizes.items() if n > 100 and n != placeholder}
    has_logo = sorted(k for k, v in out.items() if v in ok)
    print('%d of %d airlines have a logo' % (len(has_logo), len(out)))

path = os.path.join(os.path.dirname(__file__), '..', 'html', 'ui', 'airline-codes.js')
with open(path, 'w') as f:
    f.write('"use strict";\n')
    f.write('// Airline ICAO prefix -> IATA code, for airline logo lookups (ui/airlines.js).\n')
    f.write('// Generated by scripts/gen-airline-codes.py on %s from Wikidata (CC0 1.0 Universal,\n' % datetime.date.today())
    f.write('// https://creativecommons.org/publicdomain/zero/1.0/). %d airlines. Do not edit by hand.\n' % len(out))
    f.write('const AIRLINE_IATA = ')
    f.write(json.dumps(out, separators=(',', ':'), sort_keys=True))
    f.write(';\n')
    if has_logo is not None:
        f.write('// ICAO prefixes whose IATA code has a logo at the provider (probed when generated).\n')
        f.write('const AIRLINE_HAS_LOGO = new Set(%s);\n' % json.dumps(has_logo, separators=(',', ':')))
print('wrote', os.path.normpath(path), len(out), 'airlines')
